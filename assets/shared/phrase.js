const 날짜시간 = /\d{4}\s*[.\-\/년]\s*\d{1,2}\s*[.\-\/월]\s*\d{1,2}\s*일?|\d{1,2}\s*월\s*\d{1,2}\s*일|\d{1,2}\s*[:시]\s*\d{0,2}\s*분?/g, 전화번호 = /0\d{1,2}[-\s.]?\d{3,4}[-\s.]?\d{4}/g;
function 문구금지됨(raw, 규칙 = '광고') {
  let n = String(raw ?? '').normalize('NFKC').replace(/[\p{Cf}]/gu, '');
  if (규칙 === '일상' || 규칙 === '연락처') n = n.replace(날짜시간, ' ');
  if (규칙 === '연락처') n = n.replace(전화번호, ' ');
  const 붙임 = n.replace(/[\s·.\-_*~!?,'"“”‘’()\[\]{}<>|\/\\:;]+/g, '');
  return /(https?:|www\.|\.com|\.kr|\.net|@)/i.test(n) || /0\d{1,2}[-\s.]?\d{3,4}[-\s.]?\d{4}/.test(n) || /\d{7,}/.test(붙임) || /\d\s*(%|원|퍼센트|프로)/.test(n) || /\d\s*(%|원)/.test(붙임) || 문구금지1.test(n) || 문구금지2.test(붙임);
}
