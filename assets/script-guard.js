/* 대본 정책 검사 (효능 단정 표현) — 브라우저 안에서 돈다(비용 없음). 접수 서버·제작 코드도 같은 규칙표를 복사해 쓴다.
 * 쓰는 곳: script.html 의 '확정' 창. 결과: { 판정: '통과'|'경고'|'차단', 차단:[{문장,말}], 경고:[{문장,말}], 규칙 }
 * 규칙을 고칠 때는 아래 [규칙표] 두 곳만 고친다. 띄어쓰기로 빠져나가지 못하게 모든 규칙은 '공백을 지운 글'에 건다.
 * 일반 영상(쇼츠·롱폼) 대본만 검사한다(야담·분위기 영상 이야기에 '병이 낫다' 같은 말이 흔해서). */
(function () {
  var 규칙버전 = 'v1';
  // ── [규칙표 1] 막는 표현: 효능을 단정하는 말. 하나라도 있으면 그 문장은 영상으로 만들 수 없다 ──
  var 질병 = '(?:암|당뇨|고혈압|저혈압|치매|관절염|우울증|불면증|아토피|비염|통풍|고지혈증|지방간|위염|변비|탈모|골다공증|디스크|갱년기|여드름|감기|독감|코로나)';
  var 낫게함 = '(?:낫|나아|치료|치유|예방|사라|없애|없어|억제|막아|막는|고쳐|고친|잡아|해결|완화)';
  var 막는표현 = [
    ['치료·예방 단정', /(?:치료|치유|완치|예방)(?:된다|됩니다|돼요|됐어요|합니다|해요|해줘요|해줍니다|에탁월|에특효|에효과)/],
    ['병 이름과 낫는다는 말', new RegExp(질병 + '.{0,12}' + 낫게함 + '|' + 낫게함 + '.{0,12}' + 질병 + '(?!.{0,3}(?:없|아니))')],
    ['수치가 변한다는 말', /(?:혈압|혈당|콜레스테롤|체지방|중성지방)(?:이|을|가|도)?(?:내려|낮춰|낮아|떨어|빠져|줄어|줄여|잡아|조절)/],
    ['살·주름이 사라진다는 말', /(?:살이|살을|뱃살|내장지방|주름|기미|잡티|흉터|여드름|탈모)(?:이|가|을|를|도)?(?:쭉)?(?:빠|빼|사라|없어|없애|제거|지워|개선|해결)/],
    ['보증 표현', /(?:100%(?:효과|확실|보장)|무조건(?:효과|낫|좋)|특효|기적의|만병통치|부작용(?:이)?(?:전혀)?없|임상(?:에서|으로)?(?:입증|증명|검증)|식약처(?:인정|승인|허가)|fda승인)/i]
  ];
  // 부정하는 문장은 효능 단정이 아니다('치료제가 아닙니다'). 아래 말이 있으면 [규칙표 1]의 앞 4개는 건너뛴다(보증 표현은 그대로 본다)
  var 부정 = /(?:아닙니다|아니에요|아니며|아니라|않습니다|않아요|않으며|못합니다|못해요|보장하지|주장하지)/;
  // ── [규칙표 2] 경고하는 표현: 효능으로 오해될 수 있는 말. 확인하면 진행할 수 있다 ──
  var 병경고 = new RegExp(질병 + '.{0,12}(?:좋|도움|효과|추천|권해|먹으면|드시면)');   // 병 이름과 '좋다'가 함께 있으면 효능으로 읽힐 수 있다
  var 경고표현 = /(?:건강에도움|도움이(?:됩|돼|될)|면역력|항산화|피부(?:건강|관리|결)|탄력|보습|체지방|관절건강|장건강|간건강|눈건강|디톡스|활력|혈행|개선|완화)/;

  function 다듬기(t) { return String(t == null ? '' : t).normalize('NFKC').replace(/[​-‏⁠﻿­]/g, ''); }
  function 공백없이(s) { return s.replace(/[\s·ㆍ\-_.,~]+/g, ''); }
  function 자르기(글) { return 글.length > 60 ? 글.slice(0, 57) + '…' : 글; }

  function 검사(원문) {
    var 결과 = { 판정: '통과', 차단: [], 경고: [], 규칙: 규칙버전 };
    var 문장들 = 다듬기(원문).split(/[.!?。！？\n]+/);
    for (var i = 0; i < 문장들.length; i++) {
      var 문장 = 문장들[i].trim(); if (문장.length < 3) continue;
      var 붙임 = 공백없이(문장), 걸림 = false;
      var 부정문 = 부정.test(붙임);
      for (var r = 0; r < 막는표현.length && !걸림; r++) {
        if (부정문 && r < 4) continue;
        if (막는표현[r][1].test(붙임)) { 결과.차단.push({ 문장: 자르기(문장), 말: 막는표현[r][0] }); 걸림 = true; }
      }
      if (!걸림) { var m = 붙임.match(경고표현) || 붙임.match(병경고); if (m) 결과.경고.push({ 문장: 자르기(문장), 말: m[0].length > 8 ? '병 이름과 효능이 함께 나온 표현' : m[0] }); }
    }
    결과.판정 = 결과.차단.length ? '차단' : (결과.경고.length ? '경고' : '통과');
    return 결과;
  }
  window.RWScriptGuard = { 검사: 검사, 규칙버전: 규칙버전 };
})();
